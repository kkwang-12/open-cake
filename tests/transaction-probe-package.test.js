'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const {spawnSync}=require('node:child_process');
const {createRequire}=require('node:module');
const {randomBytes}=require('node:crypto');

test('isolated transaction package loads its complete runtime dependency tree',()=>{
  const root=path.resolve(__dirname,'..');
  const name='test-transaction-package-'+randomBytes(6).toString('hex');
  const directory=path.resolve(root,'artifacts',name);
  assert.ok(directory.startsWith(path.resolve(root,'artifacts')+path.sep));
  try{
    const build=spawnSync(process.execPath,['scripts/prepare-transaction-cloud.js','--package='+name],
      {cwd:root,encoding:'utf8',windowsHide:true});
    assert.equal(build.status,0,build.stderr);
    const filename=path.join(directory,'functions','jjl-d04-probe','index.js');
    const localRequire=createRequire(filename),exports={};
    const sdk={init(){},DYNAMIC_CURRENT_ENV:'test-package-env'};
    const initialize=vm.runInThisContext('(function(require,exports,process,console){'+
      fs.readFileSync(filename,'utf8')+'\n})',{filename});
    initialize(name=>name==='wx-server-sdk'?sdk:localRequire(name),exports,{env:{}},console);
    assert.equal(typeof exports.main,'function');
    assert.equal(localRequire('./package.json').dependencies['wx-server-sdk'],'4.0.2');
  }finally{
    // Only the fresh package generated by this test is removed.
    assert.ok(directory.startsWith(path.resolve(root,'artifacts')+path.sep));
    fs.rmSync(directory,{recursive:true,force:true});
  }
});
